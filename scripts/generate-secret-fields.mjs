// The device-secret field table: every configuration field that may hold a
// `vectory-secret:NAME` reference, per component section and type. It comes
// from the credential fields that scripts/generate-vector-catalog.mjs marks in
// the pinned Vector schema, and is written three times:
//
//   agent/internal/agent/secret_fields_generated.go  the agent substitutes only here
//   server/src/secret_fields.rs                      publish-time validation
//   dashboard/src/generated/secret-fields.json       the editor and device pages
//
// The agent keeps its own copy: a server never tells a device which fields to
// fill with its local secrets.
//
//   node scripts/generate-secret-fields.mjs          regenerate all three
//   node scripts/generate-secret-fields.mjs --check  fail when one is stale (CI)
import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, ".."),
  check = process.argv.includes("--check"),
  kinds = ["sources", "transforms", "sinks"];
const catalog = JSON.parse(
  await fs.readFile(
    path.join(root, "dashboard/src/generated/vector-catalog.json"),
    "utf8",
  ),
);
const segment = String.raw`(?:[A-Za-z0-9_-]+|\*)(?:\[\])*`,
  pathSyntax = new RegExp(`^${segment}(?:\\.${segment})*$`);
const rows = [];
for (const component of catalog.components) {
  if (!kinds.includes(component.kind) || !/^[a-z0-9_]+$/.test(component.type))
    throw Error(`Unexpected component ${component.kind}/${component.type}`);
  for (const field of component.sensitive_fields || []) {
    if (!pathSyntax.test(field))
      throw Error(`Unexpected field path ${component.type}: ${field}`);
    rows.push([component.kind, component.type, field]);
  }
}
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
rows.sort(
  (a, b) =>
    kinds.indexOf(a[0]) - kinds.indexOf(b[0]) ||
    compare(a[1], b[1]) ||
    compare(a[2], b[2]),
);
if (!rows.length) throw Error("The catalog lists no credential fields");
const types = new Set(rows.map(([kind, type]) => `${kind}/${type}`)).size;
const about = `${rows.length} fields in ${types} component types of Vector ${catalog.vector_version}`;
const source =
  "scripts/generate-secret-fields.mjs from dashboard/src/generated/vector-catalog.json";

const go = `// Code generated by ${source}; DO NOT EDIT.

package agent

// Regenerate with \`node scripts/generate-secret-fields.mjs\`. CI runs it with
// --check.

// secretFieldVectorVersion and secretFieldSchemaSHA256 identify the pinned
// schema this table was generated from.
const (
	secretFieldVectorVersion = ${JSON.stringify(catalog.vector_version)}
	secretFieldSchemaSHA256  = ${JSON.stringify(catalog.schema_sha256)}
)

// secretFieldTable lists every field that may hold a vectory-secret:NAME
// reference: Vector's credential fields and the reviewed plain-text
// credentials. Each entry is {section, component type, field path}; a path
// uses "." between fields, "[]" for list items and "*" for map values. The
// agent substitutes local secrets only at these paths, whatever the server
// sends.
//
// ${about}.
var secretFieldTable = [...][3]string{
${rows.map((row) => `\t{${row.map((value) => JSON.stringify(value)).join(", ")}},`).join("\n")}
}
`;

const rust = `//! Device-secret fields of the pinned Vector schema.
//!
//! Generated by ${source};
//! do not edit. Regenerate with \`node scripts/generate-secret-fields.mjs\`; CI
//! runs it with \`--check\`.

/// The Vector release the table was generated from.
pub const VECTOR_VERSION: &str = ${JSON.stringify(catalog.vector_version)};
/// Digest of the generated schema the table was read from.
pub const SCHEMA_SHA256: &str = ${JSON.stringify(catalog.schema_sha256)};

/// Every field that may hold a \`vectory-secret:NAME\` reference: Vector's
/// credential fields and the reviewed plain-text credentials, as
/// \`(section, component type, field path)\`. A path uses \`.\` between fields,
/// \`[]\` for list items and \`*\` for map values.
///
/// ${about}.
#[rustfmt::skip]
pub const SECRET_FIELDS: &[(&str, &str, &str)] = &[
${rows.map((row) => `    (${row.map((value) => JSON.stringify(value)).join(", ")}),`).join("\n")}
];
`;

const fields = {};
for (const [kind, type, field] of rows)
  ((fields[kind] ??= {})[type] ??= []).push(field);
const json =
  JSON.stringify(
    {
      generated_by: source,
      vector_version: catalog.vector_version,
      schema_sha256: catalog.schema_sha256,
      path_syntax:
        'Fields are joined with ".", "[]" marks list items and "*" marks map values.',
      field_count: rows.length,
      component_types: types,
      fields,
    },
    null,
    2,
  ) + "\n";

const outputs = [
  ["agent/internal/agent/secret_fields_generated.go", go],
  ["server/src/secret_fields.rs", rust],
  ["dashboard/src/generated/secret-fields.json", json],
];
const stale = [];
for (const [file, text] of outputs) {
  const target = path.join(root, file);
  if (check) {
    const current = await fs.readFile(target, "utf8").catch(() => null);
    if (current !== text) stale.push(file);
  } else await fs.writeFile(target, text);
}
if (stale.length) {
  console.error(
    `Stale device-secret field tables: ${stale.join(", ")}. Run node scripts/generate-secret-fields.mjs`,
  );
  process.exit(1);
}
console.log(
  `${check ? "Device-secret field tables are current" : "Wrote the device-secret field tables"}: ${about}.`,
);
